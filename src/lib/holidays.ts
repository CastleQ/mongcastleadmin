export const isHoliday = (date: string) => date in HOLIDAYS;

/** 다음 날 YYYY-MM-DD */
export function nextDay(date: string): string {
  const [y, m, d] = date.split("-").map(Number);
  const n = new Date(y, m - 1, d + 1);
  return `${n.getFullYear()}-${String(n.getMonth() + 1).padStart(2, "0")}-${String(n.getDate()).padStart(2, "0")}`;
}

export type DayType = "평일" | "금요일" | "주말";

/** 요금 구분: 토·일·공휴일 → 주말 / 금요일·공휴일 전날 → 금요일 / 그 외 평일 */
export function dayType(date: string): DayType {
  const [y, m, d] = date.split("-").map(Number);
  const dow = new Date(y, m - 1, d).getDay();
  if (dow === 0 || dow === 6 || isHoliday(date)) return "주말";
  if (dow === 5 || isHoliday(nextDay(date))) return "금요일";
  return "평일";
}
